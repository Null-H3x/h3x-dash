def run_section(title, checks):
    """Print a section's checks; return the list."""
    section(title)
    for c in checks:
        line = f"  {ICON[c.status]} {WHT}{c.name:<22}{RST} {c.message}"
        print(line)
        if c.status == FAIL and c.fix:
            print(f"      {DIM}fix: {c.fix}{RST}")
        elif c.status == WARN and c.fix:
            print(f"      {DIM}fix: {c.fix}{RST}")
    return checks


def _install_apt_batch(pkgs):
    """Single apt-get install for all apt packages — fastest."""
    if not pkgs:
        return True
    print(f"\n{CYN}── apt-get install ({len(pkgs)} packages) ──{RST}")
    cmd = ['apt-get', 'install', '-y'] + sorted(set(pkgs))
    print(f"{DIM}  sudo {' '.join(cmd)}{RST}")
    try:
        subprocess.run(['apt-get', 'update'], check=False, timeout=120)
        result = subprocess.run(cmd, check=False, timeout=600)
        if result.returncode == 0:
            print(f"{GRN}  ✓ apt packages installed{RST}")
            return True
        print(f"{RED}  ✗ apt-get exited with code {result.returncode}{RST}")
        return False
    except Exception as e:
        print(f"{RED}  ✗ apt install failed: {e}{RST}")
        return False


def _ensure_pipx():
    """Make sure pipx is available + PATH is configured."""
    if which('pipx'):
        return True
    print(f"\n{CYN}── installing pipx (prerequisite for Python tools) ──{RST}")
    try:
        subprocess.run(['apt-get', 'install', '-y', 'pipx'],
                        check=False, timeout=300)
        # ensurepath updates user shell config so ~/.local/bin is on PATH
        # for new shells. Current process keeps running until exec, so we
        # also stamp the path manually below to find pipx-installed binaries.
        subprocess.run(['pipx', 'ensurepath'], check=False, timeout=60)
        if which('pipx'):
            print(f"{GRN}  ✓ pipx installed — restart shell after install completes{RST}")
            return True
        print(f"{RED}  ✗ pipx not on PATH after install — manual intervention needed{RST}")
        return False
    except Exception as e:
        print(f"{RED}  ✗ pipx install failed: {e}{RST}")
        return False


def _install_pipx_pkgs(pkgs):
    """pipx-install each Python tool. pipx isolates each into its own venv."""
    if not pkgs:
        return True
    if not _ensure_pipx():
        print(f"{YLW}  ⚠ skipping pipx tools — install pipx first{RST}")
        return False
    print(f"\n{CYN}── pipx install ({len(pkgs)} Python tools) ──{RST}")
    # pipx runs as the invoking user, not root — sudo prefix would isolate the
    # install in root's home which the operator can't reach. Use SUDO_USER if
    # available (we were re-entered via sudo), else current user.
    real_user = os.environ.get('SUDO_USER') or os.environ.get('USER')
    all_ok = True
    for pkg in sorted(set(pkgs)):
        try:
            if real_user and real_user != 'root' and os.geteuid() == 0:
                # Drop privileges so pipx installs into the real user's home
                cmd = ['sudo', '-u', real_user, '-H', 'pipx', 'install', pkg]
            else:
                cmd = ['pipx', 'install', pkg]
            print(f"{DIM}  {' '.join(cmd)}{RST}")
            result = subprocess.run(cmd, check=False, timeout=300)
            if result.returncode == 0:
                print(f"{GRN}  ✓ {pkg}{RST}")
            else:
                print(f"{YLW}  ⚠ {pkg} install returned {result.returncode}{RST}")
                all_ok = False
        except Exception as e:
            print(f"{RED}  ✗ {pkg} install failed: {e}{RST}")
            all_ok = False
    return all_ok


def _install_binary(name, url, dest):
    """Download a single-file binary, chmod +x, move into /usr/local/bin."""
    import urllib.request
    print(f"\n{CYN}── binary install: {name} ──{RST}")
    print(f"{DIM}  url:  {url}{RST}")
    print(f"{DIM}  dest: {dest}{RST}")
    tmp = Path('/tmp') / Path(dest).name
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'H3x-Dash/installer'})
        with urllib.request.urlopen(req, timeout=60) as resp:
            tmp.write_bytes(resp.read())
        tmp.chmod(0o755)
        # mv requires root if dest is /usr/local/bin
        result = subprocess.run(['mv', str(tmp), dest],
                                  check=False, timeout=30)
        if result.returncode == 0:
            print(f"{GRN}  ✓ {name} installed at {dest}{RST}")
            return True
        print(f"{RED}  ✗ mv to {dest} failed (rc={result.returncode}) — "
              f"try: sudo mv {tmp} {dest}{RST}")
        return False
    except Exception as e:
        print(f"{RED}  ✗ {name} download failed: {e}{RST}")
        return False


def install_missing(checks):
    """
    Dispatch missing tools to the right installer by method.

    Groups by install method, then runs each group:
      - apt    : one batched apt-get install for speed
      - pipx   : per-tool pipx install (each gets its own venv)
      - binary : wget + chmod + mv per tool
    """
    apt_pkgs, pipx_pkgs, binary_specs = [], [], []

    for c in checks:
        if not isinstance(c, Check) or c.status == PASS:
            continue
        spec = c.install_spec or {}
        method = spec.get('method')
        if method == 'pipx':
            pipx_pkgs.append(spec.get('pkg', c.name))
        elif method == 'binary':
            arch = detect_arch()
            url  = spec.get('url_template', '').format(arch=arch)
            dest = spec.get('dest', f'/usr/local/bin/{c.name}')
            if url and dest:
                binary_specs.append((c.name, url, dest))
        else:
            # Default: apt. Use apt_pkg if Check carried one, else spec['pkg'],
            # else fall back to the tool name itself.
            pkg = c.apt_pkg or spec.get('pkg')
            if pkg:
                apt_pkgs.append(pkg)

    if not (apt_pkgs or pipx_pkgs or binary_specs):
        return False

    print(f"\n{YLW}{BOLD}Install plan:{RST}")
    if apt_pkgs:    print(f"  {len(apt_pkgs)} apt package(s): {', '.join(sorted(set(apt_pkgs)))}")
    if pipx_pkgs:   print(f"  {len(pipx_pkgs)} pipx package(s): {', '.join(sorted(set(pipx_pkgs)))}")
    if binary_specs:
        print(f"  {len(binary_specs)} binary download(s): "
              f"{', '.join(s[0] for s in binary_specs)}")

    try:
        ans = input(f"\n{CYN}Install these now? [y/N]{RST} ").strip().lower()
    except EOFError:
        ans = 'n'
    if ans != 'y':
        print(f"{DIM}Skipped — install manually before launching.{RST}")
        return False

    ok = True
    if apt_pkgs:    ok &= _install_apt_batch(apt_pkgs)
    if pipx_pkgs:   ok &= _install_pipx_pkgs(pipx_pkgs)
    for name, url, dest in binary_specs:
        ok &= _install_binary(name, url, dest)

    if ok:
        print(f"\n{GRN}{BOLD}All installs completed.{RST}")
    else:
        print(f"\n{YLW}Some installs had issues — re-run install.py to verify.{RST}")
    return ok


def launch_h3x_dash():
    """Exec h3x-dash.py, replacing this process."""
    target = ROOT / 'h3x-dash.py'
    if not target.is_file():
        print(f"{RED}Cannot launch — h3x-dash.py not found.{RST}")
        return
    print(f"\n{GRN}{BOLD}Launching H3x-Dash...{RST}")
    print(f"{DIM}  Dashboard will be at http://127.0.0.1:5000{RST}\n")
    os.chdir(ROOT)
    os.execvp(sys.executable, [sys.executable, str(target)])


