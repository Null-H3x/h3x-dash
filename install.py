# ── Result container ──────────────────────────────────────────────────────────
class Check:
    __slots__ = ("name", "status", "message", "fix", "apt_pkg", "critical",
                  "install_spec")

    def __init__(self, name, status, message, fix="", apt_pkg=None,
                  critical=True, install_spec=None):
        self.name         = name
        self.status       = status
        self.message      = message
        self.fix          = fix
        self.apt_pkg      = apt_pkg          # back-compat for old callsites
        self.critical     = critical
        # install_spec: dict with {method: 'apt'|'pipx'|'binary', ...}
        # Drives dispatch in install_missing(). Falls back to apt_pkg if absent.
        self.install_spec = install_spec


