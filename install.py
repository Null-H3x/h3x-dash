_KALI_PATHS = ['/usr/bin', '/usr/sbin', '/usr/local/bin', '/usr/local/sbin',
               '/bin', '/sbin', '/usr/games']


def which(tool):
    """Locate a binary — PATH first, then explicit Kali dirs (sudo-safe)."""
    found = shutil.which(tool)
    if found:
        return found
    for d in _KALI_PATHS:
        cand = os.path.join(d, tool)
        if os.path.isfile(cand) and os.access(cand, os.X_OK):
            return cand
    return None


def port_open(host, port, timeout=2.0):
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


def ensure_env_file():
    """Pre-build and configure a .env if one does not exist.

    Generates a strong random H3X_SECRET and writes the full set of settings
    config.py reads (plus a GITHUB_TOKEN placeholder used by the vetted payload-
    source updater). Never clobbers an existing .env. Returns a Check.
    """
    import secrets
    env_path = ROOT / '.env'
    if env_path.exists():
        return Check('.env', PASS, f'Present — {env_path}', critical=False)

    secret = secrets.token_hex(32)
    content = f"""# H3x-Dash environment — generated by install.py
# Real environment variables override these. Keep this file out of version
# control (already covered by .gitignore). Authorized use only.

# Flask session secret — randomly generated; change only if you must.
H3X_SECRET={secret}

# Metasploit RPC (msfrpcd -P msfrpc -S -f)
MSF_HOST=127.0.0.1
MSF_PORT=55553
MSF_PASS=msfrpc
MSF_SSL=false

# Optional: GitHub API token to raise the rate limit when the Payload page
# pulls payloads from the vetted Hak5/O.MG source repos. Leave blank to use the
# (lower) anonymous limit. A read-only/public-repo token is sufficient.
GITHUB_TOKEN=
"""
    try:
        env_path.write_text(content)
        try:
            os.chmod(env_path, 0o600)         # secret inside — restrict perms
        except OSError:
            pass
        # If launched via sudo, hand ownership back to the invoking user.
        sudo_user = os.environ.get('SUDO_USER')
        if sudo_user:
            try:
                import pwd
                pw = pwd.getpwnam(sudo_user)
                os.chown(env_path, pw.pw_uid, pw.pw_gid)
            except Exception:
                pass
        return Check('.env', PASS,
                     f'Generated {env_path.name} with a random H3X_SECRET',
                     critical=False)
    except OSError as exc:
        return Check('.env', WARN, f'Could not write .env: {exc}',
                     critical=False)


