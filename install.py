# ── Architecture detection for binary downloads ──────────────────────────────

def detect_arch() -> str:
    """Map platform.machine() to the architecture string used in release URLs."""
    import platform
    m = platform.machine().lower()
    if m in ('x86_64', 'amd64'):    return 'amd64'
    if m in ('aarch64', 'arm64'):   return 'arm64'
    if m in ('i386', 'i486', 'i586', 'i686'):  return '386'
    return 'amd64'    # safest default for modern boxes


