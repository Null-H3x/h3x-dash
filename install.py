def check_enum_tools():
    checks = []
    for tool, spec in ENUM_TOOLS.items():
        candidates = ENUM_ALIASES.get(tool, [tool])
        found = next((which(c) for c in candidates if which(c)), None)
        method = spec.get('method', 'apt')
        pkg    = spec.get('pkg', tool)

        if found:
            checks.append(Check(tool, PASS, found,
                                 apt_pkg=pkg if method == 'apt' else None,
                                 critical=False, install_spec=spec))
            continue

        # Build a fix hint that matches the install method
        if method == 'pipx':
            fix = f'pipx install {pkg}'
        elif method == 'binary':
            fix = (f'wget {spec["url_template"].format(arch=detect_arch())} '
                   f'&& chmod +x kerbrute_linux_{detect_arch()} '
                   f'&& sudo mv kerbrute_linux_{detect_arch()} {spec["dest"]}')
        else:
            fix = f'sudo apt-get install {pkg}'

        fallback_note = ENUM_FALLBACKS.get(tool, '')
        msg = f'{tool} not found — that tool will be skipped'
        if fallback_note:
            msg += f' (alternatives: {fallback_note})'

        checks.append(Check(tool, WARN, msg, fix=fix,
                             apt_pkg=pkg if method == 'apt' else None,
                             critical=False, install_spec=spec))
    return checks


